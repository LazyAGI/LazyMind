"""Generate the supported local format recipe from isolated owner databases.

Inputs must be created by each actual schema/migration owner, never a user DB.
The segment sample is produced by the pinned SQLiteStore with one collection
named col_format_template. No rows, local paths or credentials enter the recipe.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sqlite3


def shape_hash(db, core=False):
    values = [str(db.execute('PRAGMA application_id').fetchone()[0]),
              str(db.execute('PRAGMA user_version').fetchone()[0])]
    objects = list(db.execute(
        'SELECT type,name,tbl_name,sql FROM sqlite_schema '
        "WHERE sql IS NOT NULL AND name NOT GLOB 'sqlite_*' "
        'ORDER BY type COLLATE BINARY,name COLLATE BINARY'
    ))
    for row in objects:
        values.extend(row)
    if core:
        version, dirty = db.execute('SELECT version,dirty FROM schema_migrations').fetchone()
        if dirty:
            raise ValueError('dirty owner database')
        values.append(str(version))
        for version, name in db.execute('SELECT version,name FROM schema_migration_history ORDER BY version'):
            values.extend((str(version), name))
    digest = hashlib.sha256()
    for value in values:
        raw = value.encode('utf-8')
        digest.update(str(len(raw)).encode('ascii') + b':' + raw)
    return digest.hexdigest(), objects


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--database-dir', type=Path, required=True)
    parser.add_argument('--segment-template-db', type=Path, required=True)
    parser.add_argument('--lazyllm-service-db', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    families = {}
    for family in ('core', 'auth', 'lazyllm', 'segments', 'channel', 'scan', 'core-state', 'auth-state', 'scan-state'):
        with sqlite3.connect((args.database_dir / (family + '.db')).resolve().as_uri() + '?mode=ro', uri=True) as db:
            families[family] = shape_hash(db, family == 'core')[0]
    with sqlite3.connect(args.segment_template_db.resolve().as_uri() + '?mode=ro', uri=True) as db:
        objects = shape_hash(db)[1]
    template = [dict(zip(('type', 'name', 'table', 'sql'),
                         (value.replace('col_format_template', '$group') for value in row))) for row in objects]
    with sqlite3.connect(':memory:') as db:
        empty_lazyllm = shape_hash(db)[0]
    with sqlite3.connect(args.lazyllm_service_db.resolve().as_uri() + '?mode=ro', uri=True) as db:
        service_lazyllm = shape_hash(db)[0]
    args.output.write_text(
        json.dumps({'version': 2, 'families': families, 'segments': template,
                    'lazyllmVariants': sorted({empty_lazyllm, service_lazyllm})}, sort_keys=True, indent=2) + '\n'
    )
    root = Path(__file__).resolve().parents[2]
    if args.output.resolve() == root / 'local/local-runtime-manager/update-format-v2.json':
        for package, relative, owners in (
            ('main', 'backend/core/update_format_recipe.go', ('core', 'core-state')),
            ('app', 'backend/scan-control-plane/internal/app/update_format_recipe.go', ('scan', 'scan-state')),
        ):
            declarations = ''.join(
                ' expected' + ''.join(part.title() for part in family.split('-'))
                + 'FormatSHA = "' + families[family] + '"\n'
                for family in owners
            )
            (root / relative).write_text(
                '// Code generated by desktop/scripts/generate-update-format.py; DO NOT EDIT.\n'
                + 'package ' + package + '\n\nconst (\n' + declarations + ')\n'
            )


if __name__ == '__main__':
    main()

func registerAdditionalError(message string, status, code int) {
	if _, exists := errorCatalog[message]; exists {
		panic("duplicate Core error catalog message: " + message)
	}
	errorCatalog[message] = NewAppError(status, code, message)
}

func registerAdditionalErrorAlias(alias, message string, status, code int) {
	if _, exists := errorCatalog[alias]; exists {
		panic("duplicate Core error catalog alias: " + alias)
	}
	errorCatalog[alias] = NewAppError(status, code, message)
}

func registerAdditionalErrorPattern(template, message string, status, code int) {
	normalizedTemplate := normalizeErrorKey(template)
	for _, pattern := range errorPatterns {
		if pattern.template == normalizedTemplate {
			panic("duplicate Core error catalog pattern: " + template)
		}
	}
	errorPatterns = append(errorPatterns, errorPattern{
		template: normalizedTemplate,
		matcher:  compileErrorPattern(normalizedTemplate),
		appErr:   NewAppError(status, code, message),
	})
}

func compileErrorPattern(template string) *regexp.Regexp {
	var pattern strings.Builder
	pattern.WriteString("^")
	for index := 0; index < len(template); {
		percent := strings.IndexByte(template[index:], '%')
		if percent < 0 {
			pattern.WriteString(regexp.QuoteMeta(template[index:]))
			break
		}
		percent += index
		pattern.WriteString(regexp.QuoteMeta(template[index:percent]))
		if percent+1 < len(template) && template[percent+1] == '%' {
			pattern.WriteString("%")
			index = percent + 2
			continue
		}
		verb := percent + 1
		for verb < len(template) && !unicode.IsLetter(rune(template[verb])) {
			verb++
		}
		if verb >= len(template) {
			pattern.WriteString("%")
			index = percent + 1
			continue
		}
		pattern.WriteString(".+?")
		index = verb + 1
	}
	pattern.WriteString("$")
	return regexp.MustCompile(pattern.String())
}
